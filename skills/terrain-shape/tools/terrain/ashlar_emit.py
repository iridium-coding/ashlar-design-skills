@cache
def _flags(state):
    block = base_id(state)
    kind = liquid_kind(state)
    fluid = _WATER if kind == "water" or "waterlogged=true" in state else _LAVA if kind == "lava" else 0
    falls_through = block in _FALL_THROUGH
    full = block in _FULL
    # A tree attachment or plant can be a full cube, a partial support, or
    # replaceable. Ecology categories cannot establish any of these properties.
    # Layered snow is gravity-replaceable but its collision depends on the layers.
    open_cell = (falls_through and block != "minecraft:snow") or block in _TORCHES
    uncertain = not (full or open_cell or fluid)
    leaf = block in LEAVES and block.endswith("_leaves")
    surface = (full or fluid) and not leaf
    return (
        fluid
        | (_OPEN if open_cell and not fluid else 0)
        | (_UNCERTAIN if uncertain else 0)
        | (_MAY_SUPPORT_SOURCE if (full or uncertain) else 0)
        | (_UNKNOWN_HEIGHT if uncertain and not leaf else 0)
        | (_SURFACE if surface else 0)
        | (_COVER if full and not fluid else 0)
        | (_STILL if fluid and is_still(state) else 0)
        | (_FREE_LIQUID if block in {"minecraft:water", "minecraft:lava"} else 0)
        | (_GRAVITY if block in GRAVITY else 0)
        | (_FALLS_THROUGH if falls_through else 0)
    )


def surface_columns(flags: np.ndarray, y1: int) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """The NO_LEAVES surface a post-build height read measures, per column of a flags grid (x, y, z).

    Returns the highest known full block or liquid of each column (its y; the grid's top where
    there is none), whether the column has one, and whether a block of unknown shape above it (or
    anywhere in a column without one) keeps its measured height uncertain.
    """
    solid = flags & _SURFACE != 0
    y2 = y1 + flags.shape[1] - 1
    top = y2 - np.argmax(solid[:, ::-1, :], axis=1)
    has = solid.any(axis=1)
    # The server may count an unknown shape as a solid surface. Do not certify
    # its height unless a known solid/liquid above it settles the observation.
    uncertain = flags & _UNKNOWN_HEIGHT != 0
    levels_y = np.arange(y1, y2 + 1)[None, :, None]
    unsure = np.any(uncertain & ((levels_y > top[:, None, :]) | ~has[:, None, :]), axis=1)
    return top, has, unsure


def seam_ground(site: Site, x: int, z: int) -> int:
    """Read the terrain bed of one fresh column, ignoring liquid and tree cells."""
    runs = site.columns.get((x, z))
    if runs is None:
        raise ValueError(f"seam point {(x, z)} is outside the post-build site read")
    for (_, hi, state), watery in zip(reversed(runs), reversed(water_run_flags(runs))):
        block = base_id(state)
        if (
            watery
            or liquid_kind(state)
            or block in TRUNK
            or block in LEAVES
            or block in PLANTS
            or block in ATTACHED
        ):
            continue
        flags = _flags(state)
        if flags & _COVER:
            return hi
        if not flags & _OPEN:
            raise ValueError(f"cannot certify seam ground at {(x, hi, z)} for block {state}")
    raise ValueError(f"read lower to find seam ground at {(x, z)}")


def _site_grid(site):
    x1, y1, z1, x2, y2, z2 = site.box
    grid = np.empty((x2 - x1 + 1, y2 - y1 + 1, z2 - z1 + 1), np.uint16)
    for (x, z), runs in site.columns.items():
        for (lo, hi, state), watery in zip(runs, water_run_flags(runs)):
            flags = _flags(state)
            if watery and base_id(state) == "minecraft:ice":
                flags |= _ICE | _STILL
            grid[x - x1, lo - y1 : hi - y1 + 1, z - z1] = flags
    return grid


def _world_cell(indices, origin):
    return tuple(int(i) + o for i, o in zip(indices, origin))


def _first(mask):
    return np.unravel_index(mask.argmax(), mask.shape)


def _project(write, site, before, after, ground, protected, approved_cells, touched, *, mass=False):
    """Overlay occupied cells, accepting empty voxel margins outside the read."""
    offset = tuple(o - start for o, start in zip(write.origin, site.box[:3]))
    start = tuple(max(0, d) for d in offset)
    end = tuple(min(dim, d + n) for d, n, dim in zip(offset, write.codes.shape, after.shape))
    if any(a >= b for a, b in zip(start, end)):
        if write.codes.any():
            raise ValueError("write outside the site read")
        return
    region = tuple(slice(a, b) for a, b in zip(start, end))
    source = tuple(slice(a - d, b - d) for a, b, d in zip(start, end, offset))
    codes = write.codes[source]
    mask = codes != 0
    if mask.sum() != np.count_nonzero(write.codes):
        raise ValueError("write outside the site read")
    if (protected[region[0], region[2]][:, None, :] & mask).any():
        raise VerifyError("a write would change a protected column")
    original = before[region]
    projected = np.array([_flags(s) for s in write.palette], dtype=np.uint16)[codes]
    origin = _world_cell(start, site.box)
    y = np.arange(origin[1], origin[1] + codes.shape[1])[None, :, None]
    wet = original & (_FLUID | _ICE) != 0
    above_ground = y > ground[region[0], region[2]][:, None, :]
    retained = wet & above_ground
    permitted = approved_cells[region]
    loses_liquid = projected & (_FLUID | _COVER) == 0
    lowers_source = (original & _STILL != 0) & (projected & _FLUID != 0) & (projected & _STILL == 0)
    drained = mask & retained & ~permitted & (loses_liquid | lowers_source)
    if drained.any():
        cell = _world_cell(_first(drained), origin)
        raise VerifyError(
            f"write would drain existing surface liquid at {cell}; keep its liquid or cover it with solid ground"
        )
    previous = after[region]
    previous_water = previous & (_WATER | _ICE) != 0
    original_water = original & (_WATER | _ICE) != 0
    swap = (
        mask
        & ~permitted
        & (
            (original_water & (projected & _LAVA != 0))
            | ((original & _LAVA != 0) & (projected & _WATER != 0))
        )
    )
    # The mass phase may drain/refill a named body. Later phases must also
    # respect liquid placed by an earlier phase, even on approved drain cells.
    previous_swap = (previous_water & (projected & _LAVA != 0)) | (
        (previous & _LAVA != 0) & (projected & _WATER != 0)
    )
    swap |= mask & previous_swap & ~(permitted & mass)
    if swap.any():
        raise VerifyError(f"water/lava overwrite at {_world_cell(_first(swap), origin)}")
    # Every face needs a read: liquid can also react with the other kind above it.
    introduced = (
        mask
        & (projected & _FLUID != 0)
        & (((previous ^ projected) & (_FLUID | _STILL | _FREE_LIQUID) != 0) | (projected & _STILL == 0))
    )
    for axis, side in ((0, 0), (0, -1), (2, 0), (2, -1), (1, 0), (1, -1)):
        if (side == 0 and start[axis] != 0) or (side == -1 and end[axis] != after.shape[axis]):
            continue
        if axis == 1 and ((side == 0 and site.box[1] == -64) or (side == -1 and site.box[4] == 319)):
            continue
        plane = [slice(None)] * 3
        plane[axis] = slice(0, 1) if side == 0 else slice(-1, None)
        exposed = introduced[tuple(plane)]
        if exposed.any():
            idx = list(_first(exposed))
            if side == -1:
                idx[axis] = introduced.shape[axis] - 1
            raise VerifyError(
                f"new liquid at {_world_cell(idx, origin)} has an unobserved flow face; read farther"
            )
    buried = mask & wet & ~above_ground
    if buried.any():
        cell = _world_cell(_first(buried), origin)
        raise VerifyError(f"write intersects buried liquid at {cell}; revise the grading or form to keep it")
    np.copyto(after[region], projected, where=mask)
    touched[region] |= mask
    return tuple(slice(max(0, a - 1), min(limit, b + 1)) for a, b, limit in zip(start, end, after.shape))


def _check_contacts(before, after, origin, *, check_open, touched=None):
    for axis in range(3):
        a = [slice(None)] * 3
        b = a.copy()
        a[axis], b[axis] = slice(None, -1), slice(1, None)
        a, b = tuple(a), tuple(b)
        for left, right in ((_WATER, _LAVA), (_LAVA, _WATER)):
            contact = (after[a] & left != 0) & (after[b] & right != 0)
            new = contact & ((before[a] & left == 0) | (before[b] & right == 0))
            if new.any():
                cell = _world_cell(_first(new), origin)
                other = list(cell)
                other[axis] += 1
                raise VerifyError(f"new water/lava contact between {cell} and {tuple(other)}")
        if check_open:
            # Only the upper fluid can spill vertically. Both horizontal orientations matter.
            pairs = ((b, a),) if axis == 1 else ((a, b), (b, a))
            for src, dst in pairs:
                open_contact = (after[src] & _FLUID != 0) & (after[dst] & _PASSABLE != 0)
                new = open_contact & (
                    ((before[src] ^ after[src]) & _FLUID != 0)
                    | (before[dst] & _PASSABLE == 0)
                    | ((before[dst] & _UNCERTAIN != 0) & touched[dst])
                )
                if new.any():
                    idx = list(_first(new))
                    kind = "lava" if after[src][tuple(idx)] & _LAVA else "water"
                    if src == b:
                        idx[axis] += 1
                    cell = _world_cell(idx, origin)
                    raise VerifyError(
                        f"{kind} at {cell} level {cell[1]} spills into an opening; raise the bank, "
                        "plan water at that level, or set hold_shores"
                    )


def _check_updated_gravity(site, final, region, updates, phase):
    """Check gravity cells written or face-adjacent to a phase update.

    The region contains the full one-cell halo. Read each candidate's support
    from the complete projection, including support just below the halo.
    """
    gravity = final[region] & _GRAVITY != 0
    if not gravity.any():
        return
    candidates = gravity & binary_dilation(updates)  # self and the six face neighbours
    xs, ys, zs = region
    start_y = max(ys.start, 1)
    if ys.start == 0 and candidates[:, 0, :].any():
        i, k = _first(candidates[:, 0, :])
        cell = _world_cell((xs.start + i, 0, zs.start + k), site.box)
        if site.box[1] > -64:
            raise VerifyError(f"read lower to check gravity at {cell} in {phase} phase")
        raise VerifyError(f"unsupported gravity block at {cell} on the world floor in {phase} phase")
    below = final[xs, start_y - 1 : ys.stop - 1, zs]
    unsupported = candidates[:, start_y - ys.start :, :] & (below & _FALLS_THROUGH != 0)
    if unsupported.any():
        origin = _world_cell((xs.start, start_y, zs.start), site.box)
        cell = _world_cell(_first(unsupported), origin)
        raise VerifyError(f"unsupported gravity block at {cell} in {phase} phase")


def _flow_reach(blocks, site, before, final, protected):
    """Bound possible water spread, allowing every horizontal route and reset after a drop."""
    origin = site.box[:3]
    todo = deque((tuple(a - b for a, b in zip(item["pos"], origin)), 7) for item in blocks)
    if not todo:
        return []
    sources = (final & (_STILL | _WATER)) == (_STILL | _WATER)
    reached = {}

    def inside(cell):
        return all(0 <= a < n for a, n in zip(cell, final.shape))

    while todo:
        cell, remaining = todo.popleft()
        x, y, z = cell
        horizontal = ((x - 1, y, z), (x + 1, y, z), (x, y, z - 1), (x, y, z + 1))
        below, above = (x, y - 1, z), (x, y + 1, z)
        # Source creation and reach depend on one another. Promote reached cells
        # with two potential sources and a possible solid/source floor. A new
        # source can enable horizontal neighbours and the cell directly above.
        supported = inside(below) and (sources[below] or final[below] & _MAY_SUPPORT_SOURCE)
        if not sources[cell] and supported and sum(bool(sources[p]) for p in horizontal if inside(p)) >= 2:
            sources[cell] = True
            for p in (*horizontal, above):
                if p in reached and not sources[p]:
                    todo.append((p, reached[p]))
        if sources[cell]:
            remaining = 7
        if reached.get(cell, -1) >= remaining:
            continue
        reached[cell] = remaining
        if protected[x, z]:
            raise VerifyError(f"water flow could reach a protected column at {_world_cell(cell, origin)}")
        if inside(above) and final[above] & _GRAVITY:
            raise VerifyError(f"water flow could undermine a gravity block at {_world_cell(above, origin)}")
        for neighbour in (below, *horizontal, above):
            if not inside(neighbour):
                if (neighbour == below and site.box[1] == -64) or (neighbour == above and site.box[4] == 319):
                    continue
                raise VerifyError(
                    f"water from a fall could leave the site read at {_world_cell(cell, origin)}"
                )
            if final[neighbour] & _LAVA and not (before[cell] & _WATER and before[neighbour] & _LAVA):
                raise VerifyError(f"water from a fall could touch lava at {_world_cell(neighbour, origin)}")
            if neighbour == above or (neighbour != below and remaining == 0):
                continue
            if final[neighbour] & (_PASSABLE | _WATER):
                todo.append((neighbour, 7 if neighbour == below else remaining - 1))
    return [_world_cell(p, origin) for p in reached]


def _quality(box, surface_path, water, origin, heights):
    x1, y, z1, x2, top, z2 = box
    region = {"region_a": (x1, y, z1), "region_b": (x2, top, z2)}
    corners = [(x1, y, z1), (x2, y, z1), (x2, y, z2), (x1, y, z2)]
    rows = {
        "surface_match": [{**region, "file": surface_path, "tolerance": 0, "min_ratio": 0.98}],
        "seam": [{"from": p, "to": corners[(i + 1) % 4], "max_step": 1} for i, p in enumerate(corners)],
        "silhouette": [{**region, "sample_count": 9, "min_y_variance": 3}],
        "edge_irregularity": [
            {"edge_name": "terrain", "from": corners[0], "to": corners[2], "max_collinear_run": 7}
        ],
    }
    if water is not None:
        bed = surface_y(heights)
        for level in np.unique(water[np.isfinite(water)]):
            basin = water == level
            i, j = np.nonzero(basin)
            below_bed = max(-64, int(bed[basin].min()) - 1)
            rows.setdefault("water_continuity", []).append(
                {
                    "region_a": (origin[0] + int(i.min()), below_bed, origin[1] + int(j.min())),
                    "region_b": (origin[0] + int(i.max()), int(level), origin[1] + int(j.max())),
                    "level": int(level),
                }
            )
    return rows


def check_form_layers(site: Site, layers: list[tuple[str, LiveWrite]], *, max_columns: int = 128) -> list[tuple[str, LiveWrite]]:
    """Check forms-only layers against a site read, tile by tile, in order.

    For work that leaves the ground surface alone, such as designed caves.
    Each tile is projected onto the state left by the tiles before it and
    gets the same checks as the terrain emitter: no drained, overwritten or
    buried liquid, no new opening a liquid could spill into, no new
    water/lava contact and no gravity block left over a fall-through cell.

    Args:
        site: The exact site read the layers were designed against.
        layers: ``(mode, write)`` pairs in build order, e.g. ``carve`` then ``dress``.
        max_columns: Columns per tile (and so per phase file).

    Returns:
        The ``(mode, tile)`` pairs to emit, one phase each, in order.

    Raises:
        VerifyError: When a tile would break one of the checks.
    """
    ground = surfaces(site).ground
    before = _site_grid(site)
    after = before.copy()
    protected = np.zeros(ground.shape, bool)
    approved = np.zeros(before.shape, bool)
    touched = np.zeros(before.shape, bool)
    tiles = []
    for mode, write in layers:
        for tile in split_columns(write, max_columns):
            halo = _project(tile, site, before, after, ground, protected, approved, touched)
            origin = _world_cell([sl.start for sl in halo], site.box)
            _check_contacts(before[halo], after[halo], origin, touched=touched[halo], check_open=True)
            _check_updated_gravity(site, after, halo, touched[halo], mode)
            tiles.append((mode, tile))
    _check_contacts(before, after, site.box[:3], check_open=False)
    return tiles


def _prepare(hf, spec, site, recipe, water, forms, protect, bodies, max_columns, *, require_relief=True,
             check_terraces=True):
    ox = integer_level(recipe["origin"][0], "origin x")
    oz = integer_level(recipe["origin"][2], "origin z")
    xi, zi = ox - site.box[0], oz - site.box[2]
    crop = np.s_[xi : xi + hf.nx, zi : zi + hf.nz]
    surf = surfaces(site)
    ground = surf.ground
    if xi < 0 or zi < 0 or ground[crop].shape != hf.h.shape:
        raise ValueError("field outside the site read")
    drained_cells = {cell for body in bodies for cell in body.cells}
    report = verify.verify(
        hf,
        spec,
        recipe,
        ground=ground[crop],
        water=water,
        existing_water=liquid_levels(site, surf=surf, excluded=drained_cells).level[crop],
        require_relief=require_relief,
        check_terraces=check_terraces,
    )
    if not report.ok:
        raise VerifyError(str(report))
    mass = materialize_live(hf, spec, site, recipe, water=water, protect=protect, drains=bodies)
    layers = [("mass", mass)]
    form_writes = [(f.mode, form_write(f)) for f in forms]
    for mode in ("carve", "build"):
        layers.extend((mode, w) for kind, w in form_writes if kind == mode)
    falls = recipe.get("falls", [])
    flow = flow_build(falls, site=site)
    source = np.ones((1, 1, 1), np.uint16)
    writes = [w for _, w in layers]
    writes.extend(LiveWrite(tuple(b["pos"]), source, ["skip", "minecraft:water"]) for b in flow["blocks"])
    protected = np.zeros(ground.shape, bool)
    if protect is not None:
        protected[crop] = protect
    before = _site_grid(site)
    after = before.copy()
    approved_cells = np.zeros(before.shape, bool)
    for x, y, z in drained_cells:
        approved_cells[x - site.box[0], y - site.box[1], z - site.box[2]] = True
    touched = np.zeros(before.shape, bool)
    # A terrain plan can pause between any two files. Validate the intermediate
    # state of each static phase, including each tile of a large mass or form.
    for mode, write in layers:
        for tile in split_columns(write, max_columns):
            halo = _project(
                tile, site, before, after, ground, protected, approved_cells, touched, mass=mode == "mass"
            )
            origin = _world_cell([sl.start for sl in halo], site.box)
            _check_contacts(before[halo], after[halo], origin, touched=touched[halo], check_open=True)
            _check_updated_gravity(site, after, halo, touched[halo], mode)
    for write in writes[len(layers) :]:
        _project(write, site, before, after, ground, protected, approved_cells, touched)
    _check_contacts(before, after, site.box[:3], check_open=False)
    spills = liquid_violations(writes, site, falls)
    for first in spills:
        # The materializer classifies tree attachments as open. A confirmed
        # full cube in the final projection (e.g. a bee nest) seals that face.
        neighbour = first["neighbour"]
        if neighbour is not None:
            idx = tuple(v - o for v, o in zip(neighbour, site.box[:3]))
            if after[idx] & _COVER:
                continue
        raise VerifyError(
            f"{first['kind']} at {first['cell']} level {first['level']} spills "
            f"{first['contact']} {first['neighbour']}; raise the bank, plan water at "
            "that level, or set hold_shores"
        )
    reach = _flow_reach(flow["blocks"], site, before, after, protected)
    if reach:
        # Do not count potential downstream cells as direct writes. Their updates
        # can still awaken an already unsupported gravity block on any face.
        indices = np.asarray(reach, dtype=np.intp) - site.box[:3]
        lo = np.maximum(0, indices.min(axis=0) - 1)
        hi = np.minimum(after.shape, indices.max(axis=0) + 2)
        region = tuple(slice(a, b) for a, b in zip(lo, hi))
        updates = np.zeros(tuple(hi - lo), bool)
        updates[tuple((indices - lo).T)] = True
        _check_updated_gravity(site, after, region, updates, "flow")
    surface = expected_surface(hf, water, mass.kept_trunks, (ox, oz), retained=mass.liquid_top)
    # Forms can both remove and add the highest solid. Use the complete projected column.
    projected_field = after[crop[0], :, crop[1]]
    top, has, unsure = surface_columns(projected_field, site.box[1])
    surface["top"] = np.where(has, top, None).ravel().tolist()
    top_flags = np.take_along_axis(projected_field, (top - site.box[1])[:, None, :], axis=1)[:, 0, :]
    visible_water = np.where(top_flags & (_SURFACE | _WATER) == (_SURFACE | _WATER), top, np.nan)
    skip = np.asarray(surface["skip"]).reshape(hf.h.shape)
    skip[protected[crop]] = 1
    # Actual leaves are known to be ignored by NO_LEAVES; they can still take water.
    skip[unsure] = 1
    lips = {tuple(b["pos"]) for b in flow["blocks"]}
    for x, y, z in reach:
        if (x, y, z) not in lips and ox <= x < ox + hf.nx and oz <= z < oz + hf.nz:
            skip[x - ox, z - oz] = 1
    surface["skip"] = skip.ravel().tolist()
    # Count original surface liquid inside the field, plus any modified margin cells.
    affected = np.zeros(ground.shape, bool)
    affected[crop] = True
    counted = affected[:, None, :] | (before != after)
    above = np.arange(site.box[1], site.box[4] + 1)[None, :, None] > ground[:, None, :]
    original = (before & (_FLUID | _ICE) != 0) & above
    final = after & (_FLUID | _ICE) != 0
    stats = {
        "kept": int(np.count_nonzero(counted & original & final & ~touched)),
        "covered": int(np.count_nonzero(counted & original & ~final & (after & _COVER != 0))),
        "drained": int(np.count_nonzero(approved_cells & original & ~final & (after & _COVER == 0))),
        "added": int(np.count_nonzero(touched & final)),
    }
    return report, layers, flow, reach, surface, stats, visible_water


def _run(
    hf,
    spec,
    site,
    project,
    *,
    element,
    first_phase,
    recipe,
    water,
    forms,
    protect,
    standalone,
    max_columns,
    held,
    preview,
    drain_approved,
    seam_rows=None,
    extra_notes=(),
    require_relief=True,
    check_terraces=True,
):
    element = _label(element)
    first_phase = integer_level(first_phase, "first_phase")
    if first_phase < 1:
        raise ValueError("first_phase must be positive")
    if recipe is None:
        recipe = {"element": element, "origin": [site.box[0], 0, site.box[2]], "nx": hf.nx, "nz": hf.nz}
        if (hf.nx, hf.nz) != (site.box[3] - site.box[0] + 1, site.box[5] - site.box[2] + 1):
            raise ValueError("without a recipe the field must match the site box")
    _check_recipe(recipe)
    bodies = drain_bodies(site, recipe, protect=protect)
    if not preview:
        _check_approvals(bodies, drain_approved)
    report, layers, flow, reach, surface, stats, visible_water = _prepare(
        hf, spec, site, recipe, water, forms, protect, bodies, max_columns, require_relief=require_relief,
        check_terraces=check_terraces,
    )
    rows, payloads, boxes = [], [], []

    def append(name, payload, count, box, via):
        phase_id = first_phase + len(rows)
        file = f"phases/{phase_id:02d}-{name}.json"
        if site.world is not None:
            payload["world"] = site.world
        payloads.append((project / file, payload))
        rows.append(
            {
                "id": phase_id,
                "name": name,
                "file": file,
                "blocks": count,
                "from": box[:3],
                "to": box[3:],
                "via": via,
                "rollback": "backup",
            }
        )
        boxes.append(box)

    indices = {}
    for mode, write in layers:
        for tile in split_columns(write, max_columns):
            fills = greedy_fills(tile)
            box = _bounds([(*f["from"], *f["to"]) for f in fills])
            indices[mode] = indices.get(mode, 0) + 1
            append(
                f"{element}-{mode}-{indices[mode]}",
                {"fills": fills, "liquids": "static"},
                int(np.count_nonzero(tile.codes)),
                box,
                "placer",
            )
    direct_boxes = boxes.copy()
    if reach:
        direct_boxes.extend((*b["pos"], *b["pos"]) for b in flow["blocks"])
        count = len(flow["blocks"])
        box = _bounds([(*cell, *cell) for cell in reach])
        append(f"{element}-flow", flow, count, box, "mcp" if count <= 200 else "placer")
    ox, oz = surface["origin"]
    ys = [y for y in surface["top"] if y is not None]
    terrain_box = (
        ox,
        min(ys, default=site.box[1]),
        oz,
        ox + hf.nx - 1,
        max(ys, default=site.box[4]),
        oz + hf.nz - 1,
    )
    bbox = _bounds([terrain_box, *boxes])
    direct = _bounds([terrain_box, *direct_boxes])
    reach_xz = max(ox - direct[0], oz - direct[2], direct[3] - terrain_box[3], direct[5] - terrain_box[5])
    folder = Path("terrain/previews" if preview else "terrain")
    prefix = project / folder / element
    surface_name = f"{folder}/{element}.surface.json"
    quality = _quality(terrain_box, surface_name, water, (ox, oz), hf.h)
    if seam_rows is not None:
        quality["seam"] = seam_rows
    if not require_relief:
        # A gentle grading job still gets measured against its own silhouette.
        silhouette = quality["silhouette"][0]
        longer = hf.h[:, hf.nz // 2] if hf.nx >= hf.nz else hf.h[hf.nx // 2, :]
        sample = surface_y(longer[np.linspace(0, longer.size - 1, silhouette["sample_count"]).astype(int)])
        silhouette["min_y_variance"] = min(3.0, float(np.var(ys)), float(sample.var()))
    mass = layers[0][1]
    notes = [
        f"recipe {folder}/{element}.recipe.json",
        f"GATE A {verify.offline_token(report)}",
        f"{sum(row['blocks'] for row in rows):,} direct cell writes across {len(rows)} phases",
        f"removed trees: {mass.removed_trees}, farthest write {reach_xz} blocks outside the box",
        f"liquid retained {stats['kept']}, covered {stats['covered']}, added {stats['added']}; held columns {held}",
    ]
    notes.extend(extra_notes)
    notes.extend(_drain_notes(bodies))
    if bodies:
        notes.append(f"liquid cells drained {stats['drained']}")
    if reach:
        notes.append(
            f"back up the full flow box {_point(boxes[-1][:3])} to {_point(boxes[-1][3:])} before placing "
            f"{len(flow['blocks'])} source blocks; downstream spread can extend beyond the sources"
        )
    result = EmitResult(rows, quality, notes, bbox, project / surface_name, report)
    prefix.parent.mkdir(exist_ok=True, parents=True)
    render_views(hf, str(prefix), water=visible_water)
    _write_json(prefix.with_suffix(".recipe.json"), recipe)
    prefix.with_suffix(".verify.txt").write_text(
        str(report) + "\n" + "\n".join(notes) + "\n", encoding="utf-8"
    )
    _write_json(result.surface_file, surface)
    if preview:
        return result
    for path, payload in payloads:
        path.parent.mkdir(exist_ok=True, parents=True)
        _write_json(path, payload)
    snippet = plan_rows_toon(result)
    prefix.with_suffix(".plan-rows.toon").write_text(snippet, encoding="utf-8")
    if standalone:
        lines = [
            "plan:",
            f"  project: {_cell(project.resolve().name)}",
            f"  skill: {_cell(recipe.get('skill', 'terrain-shape'))}",
        ]
        if site.world is not None:
            lines.append(f"  world: {_cell(site.world)}")
        anchor = (ox, round(hf.h[0, 0]), oz)
        lines.extend(
            [
                f"  anchor: {{x: {anchor[0]}, y: {anchor[1]}, z: {anchor[2]}}}",
                f"  bbox: {{from: {list(bbox[:3])}, to: {list(bbox[3:])}}}",
                f"  summary: {_cell(recipe.get('summary') or element)}",
                "  approved: no",
            ]
        )
        (project / "plan.toon").write_text("\n".join(lines) + "\n" + snippet, encoding="utf-8")
    return result


def emit_field(
    hf: HeightField,
    spec: MaterialSpec,
    site: Site,
    project_dir: Path,
    *,
    element: str,
    first_phase: int,
    recipe: dict | None = None,
    water: np.ndarray | None = None,
    forms: list[Form] = (),
    protect: np.ndarray | None = None,
    standalone: bool = False,
    max_columns: int = 128,
    drain_approved: tuple[str, ...] = (),
    seam_rows: list[dict] | None = None,
    extra_notes: tuple[str, ...] = (),
    held_columns: int = 0,
    preview: bool = False,
    require_relief: bool = True,
    check_terraces: bool = True,
) -> EmitResult:
    return _run(
        hf,
        spec,
        site,
        Path(project_dir),
        element=element,
        first_phase=first_phase,
        recipe=recipe,
        water=water,
        forms=forms,
        protect=protect,
        standalone=standalone,
        max_columns=max_columns,
        held=held_columns,
        preview=preview,
        seam_rows=seam_rows,
        extra_notes=extra_notes,
        drain_approved=drain_approved,
        require_relief=require_relief,
        check_terraces=check_terraces,
    )


def _from_recipe(recipe, project_dir, first_phase, standalone, preview, drain_approved=()):
    _check_recipe(recipe)
    project = Path(project_dir)
    read = Path(recipe["site"]["read"])
    if read.is_absolute() or not (project / read).resolve().is_relative_to(project.resolve()):
        raise ValueError("site read must be relative to the project")
    site, _, _ = ground_for(recipe, project)
    info = {}
    hf = build_field(recipe, project, info)
    water = water_levels(hf, recipe)
    if recipe.get("material"):
        spec = _material_from_spec(recipe["material"], hf, recipe, water=water)
    else:
        spec = MaterialSpec.natural(hf, snow_y=recipe.get("snow_y"))
        if recipe.get("strata"):
            spec.strata = [(s["block"], s["thickness"]) for s in recipe["strata"]]
    forms = [load_form(f, project) for f in recipe.get("forms", [])]
    return _run(
        hf,
        spec,
        site,
        project,
        element=recipe["element"],
        first_phase=first_phase,
        recipe=recipe,
        water=water,
        forms=forms,
        protect=None,
        standalone=standalone,
        max_columns=128,
        held=info["held_columns"],
        preview=preview,
        drain_approved=drain_approved,
    )


def emit_ashlar(
    recipe: dict,
    project_dir: Path,
    *,
    first_phase: int,
    standalone: bool = False,
    drain_approved: tuple[str, ...] = (),
) -> EmitResult:
    return _from_recipe(recipe, project_dir, first_phase, standalone, False, drain_approved)


def preview_field(recipe: dict, project_dir: Path) -> EmitResult:
    return _from_recipe(recipe, project_dir, 1, False, True)
