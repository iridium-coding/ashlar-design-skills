def _check_recipe(recipe):
    for key in ("biomes", "biome_change", "biome-change", "fillbiome"):
        if recipe.get(key):
            raise ValueError(f"{key} operations cannot be generated by terrain emission")


def _drain_notes(bodies):
    return [
        f"drain {b.id} {','.join(sorted(b.kinds))} {len(b.cells)} cells; seed {_point(b.seed)}, "
        f"{len(b.columns)} columns, bounds {_point(b.bbox[:3])} to {_point(b.bbox[3:])}, "
        f"top y {b.bbox[4]}"
        for b in bodies
    ]


def _check_approvals(bodies, approved):
    if isinstance(approved, str):
        raise TypeError("drain_approved must be a sequence of body IDs")
    receipts = list(approved)
    required = {b.id for b in bodies}
    missing = sorted(required - set(receipts))
    stale = sorted(set(receipts) - required)
    if missing or stale or len(receipts) != len(set(receipts)):
        raise VerifyError(
            "drain approvals must match each previewed body exactly once; "
            f"missing {missing}, stale or unknown {stale}\n" + "\n".join(_drain_notes(bodies))
        )


def _label(value):
    if not isinstance(value, str) or not re.fullmatch(r"[a-zA-Z0-9][a-zA-Z0-9_-]*", value):
        raise ValueError(f"invalid terrain element name {value!r}")
    return value


def _point(pos):
    return " ".join(map(str, pos))


def _cell(value):
    if isinstance(value, (tuple, list)):
        return _point(value)
    if isinstance(value, str) and (any(c in value for c in ',:"{}[]\n\r\\') or value != value.strip()):
        return json.dumps(value, ensure_ascii=False)
    return str(value)


def _table(name, rows, indent=""):
    if not rows:
        return [f"{indent}{name}[0]:"]
    keys = list(rows[0])
    return [
        f"{indent}{name}[{len(rows)}]{{{','.join(keys)}}}:",
        *(f"{indent}  " + ",".join(_cell(row[k]) for k in keys) for row in rows),
    ]


def plan_rows_toon(result: EmitResult) -> str:
    notes = ",".join(json.dumps(n, ensure_ascii=False) for n in result.notes)
    lines = [f"  notes[{len(result.notes)}]: {notes}", *_table("phases", result.phases)]
    lines.append("quality_contract:")
    for key, rows in result.quality.items():
        lines.extend(_table(key, rows, "  "))
    return "\n".join(lines) + "\n"


def _bounds(boxes):
    return tuple(min(b[i] for b in boxes) if i < 3 else max(b[i] for b in boxes) for i in range(6))


def _write_json(path, value):
    path.write_text(json.dumps(value, ensure_ascii=False, allow_nan=False) + "\n", encoding="utf-8")


